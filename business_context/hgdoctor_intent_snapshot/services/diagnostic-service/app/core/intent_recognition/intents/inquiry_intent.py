"""
咨询模块 - 意图注册

当用户询问院内地点、路线、就医流程等时，识别为 inquiry 意图。
extraction_prompt 指示 LLM 对用户输入进行问题拆分。
用户可能在一句话中包含多个独立问题，需要拆分后分别处理。
拆分结果通过 extra_data.items 返回前端，前端进入咨询模块时回传。
"""

from ..models import IntentDefinition
from ..registry import IntentRegistry

INQUIRY_EXTRACTION_PROMPT = """
如果识别为 inquiry，请严格按以下规则对用户输入做“问题拆分、上下文补全和子意图分类”。只做结构化提取，不回答问题，不查询知识库。

【输出格式要求】
输出必须放在 extra_data 中，且必须保持现有字段结构：
{
  "items": [
    {
      "normalized_question": "拆分并补全后的独立问题",
      "sub_intent": "location/process/service/guidance"
    }
  ]
}

严禁输出 valid、intent、next_state、reason、extracted_symptoms 等字段；严禁把 sub_intent 改名为 intent。
items 不允许为空。每个 item 只能包含 normalized_question 和 sub_intent。
只输出 extra_data 对应的 JSON 内容，不要输出解释文字或 Markdown。

【任务】
1. 判断用户当前输入是否承接上一轮助手反问、候选选择或补充说明；若是，必须先结合最近对话补全语义，再拆分和分类。
2. 如果用户一次提出多个相互独立的问题，按顺序拆分为多个 items。
3. 如果前后有因果、承接或补充关系，合并为一个问题。
4. 每个拆分后的问题都要判断 sub_intent。
5. 用户提问地点查询和流程咨询之外的问题时，也要保留原问题并继续做子意图判断，优先归入 guidance；只有单纯症状且没有地点、流程、业务办理或现场下一步目标时，不应识别为 inquiry。

【拆分规则】
1. 多个独立问题要拆开。例如“挂号流程是什么，卫生间在哪”拆为：
   - {"normalized_question": "挂号流程是什么", "sub_intent": "process"}
   - {"normalized_question": "卫生间在哪里", "sub_intent": "location"}
   同一 sub_intent 下如果有多个独立查询对象，也必须拆开，不得只保留最后一个对象。
2. 有因果、承接、补充关系时不要拆。例如“我肚子痛卫生间在哪”保留为一个 location 问题。
3. 如果用户提到“已/已经/现在/刚刚/完成/成功/到达/在”等状态，并询问“接下来/下一步/然后/去哪/怎么办/要干嘛”，必须保留状态信息，不要拆成多个问题。
4. 用户提问地点查询和流程咨询之外的问题时，也要保留原问题并继续做子意图判断。
5. 不允许输出空 items。

【sub_intent 分类】
1. location：询问明确地点对象的位置、路线、楼层、科室、诊区、公共设施、窗口或业务办理地点；包括“在哪、在哪里、去哪、去哪里、到哪、到哪里、地点、位置、窗口在哪、怎么走、到哪里办理、哪里能办理”等；也包括院内常见购物需求，如买水、纸巾、口罩、毛巾、生活用品等，可归为超市/便利设施位置查询。
2. process：询问挂号、缴费、各项检查(如影像检查，血液检查等)、取药、住院、预约、报告领取、门诊或住院出院的复诊、互联网订单(如退款、取消、修改等)等医疗业务的流程、步骤、材料、规则、操作方法、联系方式、咨询电话、服务入口或办理/咨询方式。
3. service：用户表达要办理某项医院业务，但没有明确只问地点，也没有明确只问流程，通常需要同时给出办理流程和办理地点。
4. guidance：院内现场低风险泛化建议，或医院相关但不适合给确定流程/地点的泛化咨询。包括药物和医疗器械购买咨询、体检相关信息如时间和要求、药品质量疑问、代煎中药异常、服务投诉、退换、重做/复核/检测咨询、赔偿或法规风险类诉求、科室情况咨询，挂号服务咨询等。医院相关 guidance 必须仍识别为 inquiry。

【判定优先级】
按以下优先级判断，命中后不要继续改判。

1. 无效输入：纯语气、确认词、结束语，或只有“在哪、哪里”等没有具体对象且无法承接上下文的短句，不应识别为 inquiry；若已经被识别到 inquiry，则 normalized_question 保留原句，sub_intent 用 guidance。
   示例：“好的”“谢谢”“在哪”。

2. 就医相关泛化咨询/服务异常：医保、社保、医保码、就诊卡等就医相关常识，以及药物和医疗器械购买咨询、体检相关信息如时间和要求、药品质量、挂号服务、医院服务异常、投诉、复核检测、退换、重做、赔偿或法规责任等，只要与医院就医服务有关，sub_intent=guidance。
   服务可用性咨询：只询问指定医院/院区是否提供某项检查、治疗或服务，如“可以做X吗、能做X吗、是否开展X、有没有提供X、xx科可以看吗”，sub_intent=guidance；normalized_question 保留原问题的“是否提供/是否开展”语义，不得因为出现院区或项目名称就判为 location。

3. 联系方式/咨询方式/服务入口：如果用户询问电话、咨询电话、联系方式、热线、号码、怎么联系，或询问如何咨询、在哪里可以咨询、哪里能咨询、找谁咨询、用药咨询、药师咨询、线上咨询等服务入口/咨询方式，sub_intent=process。normalized_question 必须保留电话、联系方式、咨询、药师咨询、用药咨询等核心语义，不得改写为“XX在哪里”。
   示例：“药房咨询电话是多少” -> {"normalized_question": "药房咨询电话是多少", "sub_intent": "process"}
   示例：“在哪里可以找药师咨询” -> {"normalized_question": "如何进行药师咨询", "sub_intent": "process"}

4. 到达地点或完成步骤后的下一步：
   - “已到/到了/在 + 地点 + 现在要干嘛/下一步/接下来/然后/怎么办/做什么/要去哪”表示到达该地点后询问现场办理动作，sub_intent=process；normalized_question 必须保留“到达该地点后”的语义。
   - “已做完/办完/完成/检查完/采完血/取完药/缴完费/挂号成功”等完成动作后询问下一步，sub_intent=process；normalized_question 可改写为“完成该步骤后下一步”。
   - 如果用户用“没/未/没有/还没”等表示某步骤尚未完成，不得按完成步骤改写；仍判 process，但 normalized_question 必须保留未完成状态。
   示例：“我已经到采血处了，我现在要干嘛” -> {"normalized_question": "采血/抽血流程：到达采血处后现在该做什么", "sub_intent": "process"}

5. 同时问地点和流程：同一个问题里既有“在哪/在哪里/去哪/去哪里/到哪/地点/位置/窗口”等地点表达，又有“流程/步骤/如何/怎么操作/怎么办/需要什么材料/先做什么/规则”等流程表达时，sub_intent=service。
   示例：“去哪里缴费，缴费流程是什么” -> {"normalized_question": "缴费业务办理流程和办理地点", "sub_intent": "service"}

6. 只问地点：有“在哪/在哪里/去哪/去哪里/到哪/到哪里/地点/位置/窗口在哪/怎么走/到哪里办理/哪里能办理”等地点表达，且没有流程表达、电话/联系方式表达、咨询方式/服务入口表达时，sub_intent=location；不得改写成流程问题。
   示例：“去哪挂号”“去哪取药”“去哪拍CT”“缴费地点在哪里”“去哪里缴费” -> location。
   location 的 normalized_question 应是清晰地点查询句，并保留当前问题中的区域、楼层、院区、业务状态等限定词。
   如果用户问“有哪些/有什么/包含哪些/有哪些门诊/有哪些科室/有哪些专科”等内容查询，仍判 location，但 normalized_question 必须保留内容查询语义，不得改写为“查询对象在哪里”。
   “儿科在哪、儿科在哪里、我要去儿科、想去儿科”等无额外限定表达，统一输出“儿科在哪里”。

7. 只问流程：有“流程/步骤/如何/怎么操作/怎么办/需要什么材料/先做什么/规则”等流程表达，且没有地点表达时，sub_intent=process。
   如果当前问题和最近上下文都没有明确业务对象，不得猜测为挂号、缴费、取药等具体流程；normalized_question 必须统一输出“流程是什么”，由回答阶段反问用户想了解哪类流程。
   示例：“取药流程是什么”“如何缴费”“缴费步骤是什么” -> process；“如何挂号?” -> process。

8. 模糊业务办理：用户表达“我要/我想/需要/准备/打算 + 挂号/缴费/检查/取药/住院/预约/报告领取/拿报告/做CT/做B超/办手续”等，只说明要办理业务，没有明确问地点或流程时，sub_intent=service。
   示例：“我要缴费” -> {"normalized_question": "缴费业务办理流程和办理地点", "sub_intent": "service"}
   示例：“我想取药” -> {"normalized_question": "取药业务办理流程和办理地点", "sub_intent": "service"}

9. 院内生活用品购买：买水、纸巾、口罩、毛巾、生活用品等，sub_intent=location；normalized_question 可改写为“院内超市在哪里”。

10. 症状相关：同时有症状和明确地点/流程/业务办理/现场求助目标时，按 location/process/service/guidance 规则优先；只有单纯描述身体不适时，不应识别为 inquiry。

11. 上下文补全：
   - 当前问题承接上一轮助手反问、候选选择或补充说明时，必须先结合最近对话补全语义，再判断 sub_intent。
   - 承接形式包括区域、楼层、序号、指代词、“接下来/然后/下一步”等，也包括只回复业务对象或选项短语，如“取药”“挂号”“缴费的”。
   - 上一轮为候选列表时，当前输入若是在选择某个候选，normalized_question 必须使用该候选的完整含义。
   - 如果候选是区域/楼层且包含多个可独立前往的关键对象，normalized_question 只保留“区域/楼层 + 上一轮宽泛查询对象”的候选组合含义，不得擅自改写成其中某一个具体对象。
   - 区域/楼层候选的上一轮宽泛查询对象应从上一轮标题、反问句或用户原问题中提取，如“儿科、口腔科、检查、取药”等，不要把“包含/功能”中的多个子目标全部塞进 normalized_question。
   - 只有当前问题是完整新问题，且不是对上一轮的承接回答时，才忽略历史。
   - normalized_question 只输出补全后的独立短问题；保留区域/楼层和上一轮宽泛查询对象用于消歧不算复述历史。

12. normalized_question 必须保留用户当前问题的关键业务对象、限定词和场景，不得泛化、删减或替换。
   - “去哪挂号”不能改写为“挂号流程”
   - “去哪拍CT”不能改写为“做CT的业务办理流程和办理地点”
   - “停车缴费”不能改写为“缴费流程”
   - 不得把“某院区是否可以做X”改写为“某院区X在哪里”；必须保留用户询问的是服务是否提供、地点、流程还是办理需求
   - 不得删除或替换“电话/联系方式/咨询/药师咨询/用药咨询/线上咨询/服务入口”等核心查询对象，也不得把这类问题改写成地点问题
   - 不得删除或反转“没/未/没有/还没/已/已经/完成”等否定词或完成状态
   - valid=false 语义场景下如果仍需要填充 items，normalized_question 保留用户原始问题，sub_intent 使用 guidance

【输出示例】
用户：挂号流程是什么，卫生间在哪
extra_data:
{"items":[{"normalized_question":"挂号流程是什么","sub_intent":"process"},{"normalized_question":"卫生间在哪里","sub_intent":"location"}]}

用户：我已经到采血处了，现在要干嘛
extra_data:
{"items":[{"normalized_question":"采血/抽血流程：到达采血处后现在该做什么","sub_intent":"process"}]}

用户：药房咨询电话是多少
extra_data:
{"items":[{"normalized_question":"药房咨询电话是多少","sub_intent":"process"}]}

用户：去哪取药
extra_data:
{"items":[{"normalized_question":"取药地点在哪里","sub_intent":"location"}]}
""".strip()


def register_inquiry_intent(registry: IntentRegistry) -> None:
    """注册咨询意图到 IntentRegistry。

    Args:
        registry: 意图注册表实例
    """
    registry.register(
        IntentDefinition(
            name="info_inquiry",
            description="用户询问明确地点、位置、路线、楼层、科室位置或就医流程（挂号、缴费、检查、取药、住院等步骤）。只要问题中有明确查询对象，并询问“在哪、去哪里、怎么走”等地点信息。包括要求导航/带路到某科室（如“导航去皮肤科”“带我去骨科”），这是问位置路线、属 location，不是挂号。",
            examples=[
                "内科在哪里",
                "取药流程是什么",
                "卫生间在哪",
                "缴费窗口怎么走",
                "住院需要什么手续",
                "CT室在几楼",
                "我要去抽血",
                "退号时间",
                "开出生证明",
                "导航去皮肤科",
                "皮肤科怎么走",
                "带我去骨科",
                "体检有什么要注意的",
                "挂不上号怎么办",
                "如何挂号",
            ],
            extraction_prompt=INQUIRY_EXTRACTION_PROMPT,
            priority=2,
        )
    )
