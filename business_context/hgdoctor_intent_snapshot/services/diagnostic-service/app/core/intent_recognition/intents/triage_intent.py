"""
导诊模块 - 意图注册

当用户有就医/挂号需求时，识别为 triage 意图。
包括但不限于：描述身体不适/症状、表达就医目的（体检、疫苗、保健、拔牙等）。
extraction_prompt 指示 LLM 在识别阶段同时提取症状关键词，
结果通过 extra_data.extracted_symptoms 返回前端。
"""

from ..models import IntentDefinition
from ..registry import IntentRegistry


def register_triage_intent(registry: IntentRegistry) -> None:
    """注册导诊意图到 IntentRegistry。

    Args:
        registry: 意图注册表实例
    """
    registry.register(
        IntentDefinition(
            name="triage",
            description=(
                "用户表达了需要挂号就医、但**还不知道该挂哪个科、需要系统推荐**的意图。包括以下两大类：\n"
                "1. 身体不适/症状描述：用户描述了具体的症状或不舒服，需要看病。\n"
"2. 医疗服务需求：用户明确要做某项需要挂号的医疗服务（如疫苗接种、体检、儿童保健、"
                "拔牙、洗牙、产检、复查、换药、拆线，以及注射/用药处置类如打破伤风、注射免疫球蛋白、"
                "狂犬疫苗、输液、打针等），这些同样需要挂号到对应科室。\n"
"  即使用户只给出【具体的】医疗服务/药品处置名称（如'打破伤风'、'免疫球蛋白'、'狂犬疫苗'、"
                "'体检'、'拔牙'）、没有描述症状，也应判 triage（由系统推荐对应科室）。\n"
                "  但要区分：仅说笼统的'挂号/我要挂号/需要挂号'（既无症状、也无具体科室或具体服务名）"
                "不是本类，应判 idle 让系统追问。\n"
                "判定原则：用户的最终目的是'需要到某个科室就诊或接受医疗服务'，且**没有点名具体科室**，"
                "需要根据症状/需求推荐科室。\n"
                "【重要排除】如果用户已经**明确点名了某个具体科室**、就是要直接挂那个科的号"
                "（如'我要挂消化内科'、'挂个心内科'），应判定为 registration，不是 triage。"
            ),
            examples=[
                "我头疼",
                "最近总是咳嗽",
                "肚子痛好几天了",
                "发烧了怎么办",
                "嗓子疼，还有点流鼻涕",
                "我腰疼得厉害",
                "最近总觉得胸闷",
                "孩子拉肚子",
                "头疼应该挂什么科",
                "肚子痛看哪个科室",
                "想打疫苗挂什么科",
                "我小孩要做保健",
                "我要拔牙",
                "想洗个牙",
                "来做产检的",
                "我要来复查",
                "成人打破伤风",
                "打破伤风免疫球蛋白",
                "来打狂犬疫苗",
                "要注射免疫球蛋白",
            ],
            extraction_prompt=(
                "【重要】只要用户输入中包含了具体症状（如'月经不调'、'头疼'、'咳嗽'）或明确的医疗服务需求（如'打疫苗'、'体检'），就应判定为 triage，即使句尾是'看什么科'、'挂什么科'。\n"
                "【区分 registration】若用户已经点名了某个具体科室、就是要挂那个科（如'我要挂消化内科'、'挂个心内科'、'挂号皮肤科'），判 registration，不判 triage；\n"
                "  但若用户只是问'该挂什么科'、'看哪个科室'（没有点名，需要推荐），仍判 triage。\n"
                "但如果用户是在询问某项医疗服务是否需要挂号或预约，以及办理流程、步骤、材料、规则、时间、电话、联系方式等，属于医院业务咨询，应判定为 inquiry，不得仅因为出现“体检、疫苗、拔牙、产检”等医疗服务名称而判定为 triage。"
                "仅当用户完全没有提及具体症状或医疗服务（如只说'不舒服'、'我要挂号'、'推荐科室'），才判定为 idle。\n"
                "判定为 triage 时，extra_data 输出空对象 {} 即可，不需要提取任何字段。"
            ),
            priority=1,
        )
    )
